import { expect, test } from "@playwright/test";
import { fileURLToPath } from "node:url";
import { readFile } from "node:fs/promises";

const fixture = fileURLToPath(new URL("../../tests/fixtures/pdfjs/rotation.pdf", import.meta.url));

test("marks an area and downloads a redacted copy", async ({ page }) => {
  test.setTimeout(120_000);
  await page.goto("/#redact");
  await expect(page.getByRole("heading", { name: "Redact" })).toBeVisible();
  const chooser = page.waitForEvent("filechooser");
  await page.locator(".drop").focus();
  await page.keyboard.press("Enter");
  await (await chooser).setFiles(fixture);
  await expect(page.getByText(/exported PDF converts every page to an image/)).toBeVisible();
  const action = page.locator(".actions").getByRole("button", { name: "Redact", exact: true });
  await expect(action).toBeDisabled();
  await page.locator(".pages .sheet").first().click();
  const editor = page.getByRole("dialog", { name: "Mark areas on page 1" });
  await expect(editor.locator("canvas")).toBeVisible();
  const box = await editor.locator("canvas").boundingBox();
  await page.mouse.move(box.x + box.width * 0.2, box.y + box.height * 0.2);
  await page.mouse.down();
  await page.mouse.move(box.x + box.width * 0.6, box.y + box.height * 0.3);
  await page.mouse.up();
  await expect(editor.getByText("1 area marked on this page.")).toBeVisible();
  await editor.getByRole("button", { name: "Done" }).click();
  await expect(action).toBeEnabled();
  await action.click();
  await expect(page.getByText("Created a redacted copy of 2 pages.")).toBeVisible();
  const download = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download rotation-redacted.pdf" }).click();
  const higher = await download;
  expect(higher.suggestedFilename()).toBe("rotation-redacted.pdf");
  const higherBytes = await readFile(await higher.path());
  expect(higherBytes.includes(Buffer.from("/FlateDecode"))).toBeTruthy();
  await page.getByLabel("Smaller file").check();
  await expect(page.getByRole("link", { name: "Download rotation-redacted.pdf" })).toHaveCount(0);
  await action.click();
  await expect(page.getByText("Created a redacted copy of 2 pages.")).toBeVisible();
  const smallerDownload = page.waitForEvent("download");
  await page.getByRole("link", { name: "Download rotation-redacted.pdf" }).click();
  const smaller = await smallerDownload;
  const smallerBytes = await readFile(await smaller.path());
  expect(smallerBytes.includes(Buffer.from("/Width 1400"))).toBeTruthy();
  expect(smallerBytes.includes(Buffer.from("/DCTDecode"))).toBeFalsy();
  expect(smallerBytes.length).toBeLessThan(higherBytes.length);
  await page.locator(".pages .sheet").first().click();
  await editor.getByRole("button", { name: "Undo last mark" }).click();
  await editor.getByRole("button", { name: "Done" }).click();
  await expect(action).toBeDisabled();
  await expect(page.getByRole("link", { name: "Download rotation-redacted.pdf" })).toHaveCount(0);
});
